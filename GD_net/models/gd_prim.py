class TanhClamp(nn.Module):
    """
    Vektorwertige weiche Clamp-Funktion über Tanh.
    
    f(x) = hw * tanh(k * (x - center) / hw) + center
    mit center = (upper + lower) / 2,  hw = (upper - lower) / 2
    
    Args:
        Lz:  (z_dim,)  → lower bound = -Lz
        Uz:  (z_dim,)  → upper bound =  Uz
        sharpness: float, Steilheit des Tanh (1.0 = weich, 10+ ≈ hart)
        learnable_sharpness: bool, ob k als Parameter lernbar ist
    """
    
    def __init__(
        self,
        Lz: torch.Tensor,
        Uz: torch.Tensor,
        sharpness: float = 5.0,
        learnable_sharpness: bool = False,
    ):
        super().__init__()
        
        # Bounds als Buffer (wandern mit .to(device), werden nicht optimiert)
        self.register_buffer("Lz", Lz)   # (z_dim,)
        self.register_buffer("Uz", Uz)   # (z_dim,)
        
        # Abgeleitete Größen (auch Buffer, da deterministisch aus Lz/Uz)
        lower = -Lz
        upper = Uz
        self.register_buffer("center", (upper + lower) / 2)   # (z_dim,)
        self.register_buffer("half_width", (upper - lower) / 2)  # (z_dim,)
        
        # Steilheitsparameter
        if learnable_sharpness:
            # softplus → immer > 0
            self.log_sharpness = nn.Parameter(
                torch.tensor(torch.log(torch.tensor(sharpness)))
            )
        else:
            self.register_buffer("k", torch.tensor(float(sharpness)))
    
    @property
    def k(self) -> torch.Tensor:
        if hasattr(self, "log_sharpness"):
            return torch.exp(self.log_sharpness)
        return self._k  # buffer
    
    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """
        x: (batch, z_dim) oder (z_dim,)
        →  gleiche Shape
        """
        # Broadcast: center, half_width, k → (z_dim,)
        scaled = self.k * (x - self.center) / self.half_width
        return self.half_width * torch.tanh(scaled) + self.center
    
    def extra_repr(self) -> str:
        return (
            f"bounds=[-{self.Lz.min():.4f}, {self.Uz.max():.4f}], "
            f"sharpness={self.k.item():.2f}"
        )

class GDPRIM(nn.Module):
    '''
    Full standard learnable gradientt descent without weight sharing
    '''
    def __init__(self,mat_dim = 6,input_dim = 2,num_steps:int=10,problem_parameters:dict={}):
        super().__init__()
        # set the datatype of the parameters to be uniform in the whole network
        self.dtypus = problem_parameters["dtype"]
        # load the dpc files generated by matlab
        to_load = "QP_parameters_SS.mat"
        own_dic = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
        dpc_parameters = loadmat(os.path.join(own_dic,f"mat_files_{problem_parameters["N"]}",to_load))
        self.n_regios = num_steps
        # Setup the gradients
        G =  dpc_parameters["G"]
        H = dpc_parameters["H"]
        AA = dpc_parameters["Kx"]
        BB = dpc_parameters["Ku"]
        self.N = problem_parameters["N"]
        self.m = problem_parameters["m"]
        self.n = problem_parameters["n"]
        Hinv = np.linalg.inv(H)
        E = dpc_parameters["E"]
        F = dpc_parameters["F"]
        d = dpc_parameters["d"]
        # Setup the affine initialization
        # G_implicit = dpc_parameters["G_implicit"]
        Uz = d[0:Hinv.shape[0],0]
        Lz = d[Hinv.shape[0]:,0]
        a_std = 1/np.max(np.linalg.eigh(H).eigenvalues)
        a_in = np.log(np.exp(a_std)-1)
        self.dual_n_steps = 2
        GGT = G@G.T
        a_ggt = 1/np.max(np.linalg.eigh(GGT).eigenvalues)

        
        self.H      = nn.ParameterList(nn.Parameter(torch.tensor(H,  dtype=self.dtypus),requires_grad = True) for _ in range(num_steps))
        self.F      = nn.ParameterList(nn.Parameter(torch.tensor(F, dtype=self.dtypus),requires_grad = True) for _ in range(num_steps))
        self.dz     = nn.ParameterList(nn.Parameter(torch.zeros(self.N*(self.m+self.n), dtype=self.dtypus),requires_grad = True) for _ in range(num_steps))
        self.alphas = nn.ParameterList(nn.Parameter(torch.tensor(a_in, dtype=self.dtypus),requires_grad = True) for _ in range(num_steps))

        self.G_implicit  = nn.Parameter(torch.tensor(-Hinv@F, dtype=self.dtypus),requires_grad = True)
        self.h_implicit  = nn.Parameter(torch.zeros(self.N*(self.m+self.n), dtype=self.dtypus),requires_grad = True)
        # self.z_m0_lin    = nn.Parameter(torch.zeros((self.N*self.m,self.n),dtype=self.dtypus),requires_grad = True)

        
        
        # For comparisson with a randomly initialized network
        # self.H      = nn.ParameterList(nn.Parameter(torch.rand(H.shape,  dtype=self.dtypus),requires_grad = True) for _ in range(num_steps))
        # self.F      = nn.ParameterList(nn.Parameter(torch.rand(F.shape, dtype=self.dtypus),requires_grad = True) for _ in range(num_steps))
        # self.dz     = nn.ParameterList(nn.Parameter(torch.rand(self.N*(self.m+self.n), dtype=self.dtypus),requires_grad = True) for _ in range(num_steps))
        # self.alphas = nn.ParameterList(nn.Parameter(torch.rand(a_in.shape, dtype=self.dtypus),requires_grad = True) for _ in range(num_steps))

        # self.znull   = nn.Parameter(torch.rand(self.N*(self.m+self.n), dtype=self.dtypus),requires_grad = True)
        # self.G_imp       = nn.Parameter(torch.rand(G_implicit.shape, dtype=self.dtypus),requires_grad = True)
        # self.h_imp       = nn.Parameter(torch.zeros(G_implicit.shape[0], dtype=self.dtypus),requires_grad = True)
        
        self.register_buffer("Hinv",   torch.tensor(Hinv, dtype = self.dtypus))
        self.register_buffer("GGT",    torch.tensor(GGT  ,dtype = self.dtypus))
        self.register_buffer("a_G",    torch.tensor(a_ggt,dtype = self.dtypus))
        self.register_buffer("AA",     torch.tensor(AA,   dtype = self.dtypus))
        self.register_buffer("BB",     torch.tensor(BB,   dtype = self.dtypus))
        self.register_buffer("d",      torch.tensor(d,    dtype = self.dtypus))
        self.register_buffer("E",      torch.tensor(E,    dtype = self.dtypus))
        self.register_buffer("F_final",torch.tensor(F,    dtype = self.dtypus))
        self.register_buffer("H_final",torch.tensor(H,    dtype = self.dtypus))
        self.register_buffer("G",      torch.tensor(G,    dtype = self.dtypus))
        self.register_buffer("Lz",     torch.tensor(Lz,   dtype = self.dtypus))
        self.register_buffer("Uz",     torch.tensor(Uz,   dtype = self.dtypus))
        self.z_clamp = TanhClamp(self.Lz,self.Uz,sharpness= 10.0,learnable_sharpness = False)
        self.u_clamp = TanhClamp(self.Lz[0:self.N*self.m],self.Uz[0:self.N*self.m],sharpness = 5.0,learnable_sharpness = False)
        return

    def dual_pgd(self, GGT,G, g,a_G = 1e-2,lam0=None):
        """
        Calculate the dual solution to a found primal solution
        G:   (n_cons, z_dim)
        GGT: (n_cons, n_cons)  = G @ G.T
        g:   (B, z_dim)
        →   lam: (B, n_cons)
        """
        B = g.shape[0]
        n_cons = G.shape[0]
        
        Gg = g @ self.G.T                        # (B, n_cons)
        if lam0 is None:
            lam = torch.zeros(B, n_cons, device=g.device, dtype=g.dtype)
        else:
            lam = lam0
        for _ in range(self.dual_n_steps):
            grad = (lam @ GGT.T + Gg)  # (B, n_cons)
            lam = torch.relu(lam - a_G * grad)
        
        return lam

    def forward(self, xy: torch.Tensor):
        # --------------------------------------------------------------
        # 1. Geräte‑/dtype‑Konsistenz
        # --------------------------------------------------------------
        Hinv = self.Hinv.to(xy)
        G    = self.G.to(xy)
        GGT  = self.GGT.to(xy)
        E    = self.E.to(xy)
        F_final    = self.F_final.to(xy)
        H_final    = self.H_final.to(xy)
        d    = self.d.to(xy)
        Lz   = self.Lz.to(xy)
        Uz   = self.Uz.to(xy)
        a_G  = self.a_G.to(xy)

        # --------------------------------------------------------------
        # 2. z0 zum richtigen Shape bringen und broadcasten
        # --------------------------------------------------------------
        batch_size = xy.shape[0]
        
        # zm0 = self.u_clamp(xy@self.z_m0_lin.T)
        # zmxy= torch.concat((xy,zm0),dim=1)
        # zn0 = zmxy@self.G_imp.T
        # zk = torch.concat((zm0,zn0),dim=1)
        zk =  torch.clamp(xy@self.G_implicit.T + self.h_implicit,min=-Lz,max=Uz)#torch.zeros((batch_size,lam_shape), device=xy.device, dtype=xy.dtype)

        # --------------------------------------------------------------
        # 3. Ergebnisliste – enthält bereits den (broadcasteten) Startwert
        # --------------------------------------------------------------
        z_list = [zk]                           # (batch, z_dim)
        z_hat_list = [zk]                           # (batch, z_dim)
        lam_k = torch.zeros((batch_size,G.shape[0]) ,device = xy.device, dtype = xy.dtype)   # (batch, lam_dim)
        lam_list= [lam_k]
        # --------------------------------------------------------------
        # 4. Iterative Dual‑Gradient‑Descent‑Schritte
        # --------------------------------------------------------------
        for i in range(self.n_regios):
            H_sym = 0.5 * self.H[i] + 0.5 * self.H[i].T   # (z_dim, z_dim)

            term1 = zk @ H_sym         # (batch, z_dim)
            term2 = xy @ self.F[i].T +self.dz[i]      # (batch, z_dim)

            step = torch.nn.functional.softplus(self.alphas[i])
            zkp1_hat = zk - step * (term1 + term2) 
            zkp1 = torch.clamp(input=zkp1_hat,min=-Lz,max=Uz)
            z_list.append(zkp1)
            g = zkp1 @ H_final + xy @ F_final.T
            lam_k = self.dual_pgd(GGT=GGT,G=G,g=g,a_G=a_G).to(xy)
            lam_list.append(lam_k)
            z_hat_list.append(zkp1_hat)
            zk = zkp1

        # --------------------------------------------------------------
        # 5. Stapeln → (batch, z_dim, n_steps+1)
        # --------------------------------------------------------------
        z = torch.stack(z_list, dim=2)
        z_hat = torch.stack(z_hat_list, dim=2)
        lam = torch.stack(lam_list, dim=2)
        return z, z_hat, lam